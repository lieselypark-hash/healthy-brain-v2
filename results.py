"""
Plot training results from the CSV generated by train.py.

Usage
-----
python results.py
python results.py --metrics results/training_metrics.csv
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import os
import sys


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot success rate and reward over episodes."
    )
    parser.add_argument(
        "--metrics",
        type=str,
        default="results/training_metrics.csv",
        help="Path to metrics CSV generated by train.py or evaluate.py.",
    )
    parser.add_argument(
        "--success_out",
        type=str,
        default="results/success_rate.png",
        help="Output path for success-rate plot.",
    )
    parser.add_argument(
        "--reward_out",
        type=str,
        default="results/reward.png",
        help="Output path for reward plot.",
    )
    parser.add_argument(
        "--rolling_window",
        type=int,
        default=50,
        help="Window size for reward rolling mean.",
    )
    parser.add_argument(
        "--title_prefix",
        type=str,
        default="",
        help="Optional title prefix, e.g. 'Training' or 'Evaluation'.",
    )
    return parser.parse_args()


def ensure_plot_runtime() -> None:
    """Re-launch with workspace venv if matplotlib is missing in current Python."""
    if importlib.util.find_spec("matplotlib") is not None:
        return

    if os.environ.get("HB_RESULTS_REEXEC") == "1":
        return

    repo_root = os.path.dirname(os.path.abspath(__file__))
    venv_python = os.path.join(repo_root, ".venv", "bin", "python")
    if os.path.exists(venv_python):
        env = os.environ.copy()
        env["HB_RESULTS_REEXEC"] = "1"
        os.execve(venv_python, [venv_python, os.path.abspath(__file__), *sys.argv[1:]], env)


def load_metrics(path: str) -> dict:
    episodes = []
    rewards = []
    success_values = []
    started_values = []
    cumulative_success = []
    rolling_success = []
    cumulative_start = []
    rolling_start = []

    with open(path, "r", encoding="utf-8") as fp:
        reader = csv.DictReader(fp)
        for row in reader:
            episodes.append(int(row["episode"]))
            reward_value = row.get("episode_reward", row.get("reward", "0"))
            rewards.append(float(reward_value))

            if "success" in row and row["success"] != "":
                success_values.append(float(row["success"]))
            else:
                success_values.append(0.0)

            if "started_task" in row and row["started_task"] != "":
                started_values.append(float(row["started_task"]))
            else:
                started_values.append(0.0)

            if "cumulative_success_rate" in row and row["cumulative_success_rate"] != "":
                cumulative_success.append(float(row["cumulative_success_rate"]))
            else:
                cumulative_success.append(float(sum(success_values) / len(success_values)))

            if "rolling_success_rate" in row and row["rolling_success_rate"] != "":
                rolling_success.append(float(row["rolling_success_rate"]))
            else:
                rolling_success.append(float(cumulative_success[-1]))

            if "cumulative_start_rate" in row and row["cumulative_start_rate"] != "":
                cumulative_start.append(float(row["cumulative_start_rate"]))
            else:
                cumulative_start.append(float(sum(started_values) / len(started_values)))

            if "rolling_start_rate" in row and row["rolling_start_rate"] != "":
                rolling_start.append(float(row["rolling_start_rate"]))
            else:
                rolling_start.append(float(cumulative_start[-1]))

    if not episodes:
        raise ValueError("Metrics file is empty; no episodes to plot.")

    return {
        "episodes": episodes,
        "rewards": rewards,
        "success": success_values,
        "started": started_values,
        "cumulative_success": cumulative_success,
        "rolling_success": rolling_success,
        "cumulative_start": cumulative_start,
        "rolling_start": rolling_start,
    }


def _rolling_mean(values: list[float], window: int) -> list[float]:
    if window <= 1:
        return [float(v) for v in values]
    out = []
    running_sum = 0.0
    for idx, val in enumerate(values):
        running_sum += val
        if idx >= window:
            running_sum -= values[idx - window]
        denom = min(idx + 1, window)
        out.append(running_sum / denom)
    return out


def plot_success(metrics: dict, out_path: str, title_prefix: str = "") -> None:
    mpl_config_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".mplconfig")
    os.makedirs(mpl_config_dir, exist_ok=True)
    os.environ.setdefault("MPLCONFIGDIR", mpl_config_dir)
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(1, 1, figsize=(10, 4.8))
    ax.plot(
        metrics["episodes"],
        metrics["cumulative_success"],
        label="Cumulative success rate",
        linewidth=2.0,
    )
    ax.plot(
        metrics["episodes"],
        metrics["rolling_success"],
        label="Rolling success rate",
        linewidth=1.8,
        alpha=0.9,
    )
    ax.plot(
        metrics["episodes"],
        metrics["cumulative_start"],
        label="Cumulative task-start rate",
        linewidth=1.6,
        alpha=0.8,
    )
    ax.plot(
        metrics["episodes"],
        metrics["rolling_start"],
        label="Rolling task-start rate",
        linewidth=1.4,
        alpha=0.75,
    )
    ax.set_ylabel("Success rate")
    ax.set_xlabel("Episode")
    ax.set_ylim(0.0, 1.0)
    base_title = "Success Rate Over Episodes"
    ax.set_title(f"{title_prefix} {base_title}".strip())
    ax.grid(alpha=0.3)
    ax.legend()

    fig.tight_layout()
    fig.savefig(out_path, dpi=160)
    plt.close(fig)


def plot_reward(
    metrics: dict,
    out_path: str,
    rolling_window: int = 50,
    title_prefix: str = "",
) -> None:
    mpl_config_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".mplconfig")
    os.makedirs(mpl_config_dir, exist_ok=True)
    os.environ.setdefault("MPLCONFIGDIR", mpl_config_dir)
    import matplotlib.pyplot as plt

    reward_smoothed = _rolling_mean(metrics["rewards"], max(1, rolling_window))

    fig, ax = plt.subplots(1, 1, figsize=(10, 4.8))
    ax.plot(
        metrics["episodes"],
        metrics["rewards"],
        linewidth=1.1,
        alpha=0.35,
        label="Episode reward",
    )
    ax.plot(
        metrics["episodes"],
        reward_smoothed,
        linewidth=2.0,
        label=f"Reward rolling mean ({rolling_window})",
    )
    ax.set_xlabel("Episode")
    ax.set_ylabel("Reward")
    base_title = "Reward Over Episodes"
    ax.set_title(f"{title_prefix} {base_title}".strip())
    ax.grid(alpha=0.3)
    ax.legend()

    fig.tight_layout()
    fig.savefig(out_path, dpi=160)
    plt.close(fig)


def generate_plots_from_metrics(
    metrics_path: str,
    success_out: str,
    reward_out: str,
    rolling_window: int = 50,
    title_prefix: str = "",
) -> tuple[str, str]:
    metrics = load_metrics(metrics_path)
    success_dir = os.path.dirname(success_out)
    reward_dir = os.path.dirname(reward_out)
    if success_dir:
        os.makedirs(success_dir, exist_ok=True)
    if reward_dir:
        os.makedirs(reward_dir, exist_ok=True)

    plot_success(metrics, success_out, title_prefix=title_prefix)
    plot_reward(
        metrics,
        reward_out,
        rolling_window=rolling_window,
        title_prefix=title_prefix,
    )
    return success_out, reward_out


def main() -> None:
    ensure_plot_runtime()
    args = parse_args()
    if not os.path.exists(args.metrics):
        raise FileNotFoundError(f"Metrics file not found: {args.metrics}")

    success_path, reward_path = generate_plots_from_metrics(
        metrics_path=args.metrics,
        success_out=args.success_out,
        reward_out=args.reward_out,
        rolling_window=args.rolling_window,
        title_prefix=args.title_prefix,
    )
    print(f"Saved success plot → {success_path}")
    print(f"Saved reward plot → {reward_path}")


if __name__ == "__main__":
    main()
